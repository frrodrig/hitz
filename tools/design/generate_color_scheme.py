#!/usr/bin/env python3
"""Generates core/designsystem/.../theme/Color.kt from the Hitz brand seeds.

Uses the Material Color Utilities algorithm (``pip install materialyoucolor``), so the light
and dark schemes keep Material 3 tone relationships and contrast. Run it again after changing
a seed:

    python3 tools/design/generate_color_scheme.py
"""
from __future__ import annotations

from pathlib import Path

from materialyoucolor.dynamiccolor.dynamic_scheme import DynamicScheme
from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors as M
from materialyoucolor.dynamiccolor.variant import Variant
from materialyoucolor.hct import Hct
from materialyoucolor.palettes.tonal_palette import TonalPalette

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "core/designsystem/src/main/kotlin/eus/hitz/core/designsystem/theme/Color.kt"

# Brand seeds
SEEDS = {
    "primary": 0xFF385F97,    # Itsaso blue (the sea, the txapela)
    "secondary": 0xFF1F6F78,  # Cantabrian sea teal
    "tertiary": 0xFFB7791F,   # Ochre, like late-summer fields
}
# Red (#D7263D) is kept for illustration (icon, mascot) and errors only, never for UI roles.
NEUTRAL = (60.0, 5.0)          # warm cream neutral (hue, chroma)
NEUTRAL_VARIANT = (60.0, 9.0)

# Extended (answer feedback) seeds
EXTENDED = {
    "success": 0xFF2E8B57,
    "warning": 0xFFE0A100,
}

# Calmer chroma where the default (48) is too loud for large containers.
EXTENDED_CHROMA = {"success": 30.0}

ROLES = [
    "primary", "onPrimary", "primaryContainer", "onPrimaryContainer",
    "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
    "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
    "error", "onError", "errorContainer", "onErrorContainer",
    "background", "onBackground", "surface", "onSurface",
    "surfaceVariant", "onSurfaceVariant", "outline", "outlineVariant",
    "scrim", "inverseSurface", "inverseOnSurface", "inversePrimary", "surfaceTint",
    "surfaceDim", "surfaceBright", "surfaceContainerLowest", "surfaceContainerLow",
    "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
]


def palette(argb: int, chroma: float | None = None) -> TonalPalette:
    hct = Hct.from_int(argb)
    return TonalPalette.from_hue_and_chroma(hct.hue, chroma if chroma is not None else max(hct.chroma, 48.0))


def scheme(dark: bool, contrast: float) -> DynamicScheme:
    return DynamicScheme(
        source_color_hct=Hct.from_int(SEEDS["primary"]),
        variant=Variant.TONAL_SPOT,
        contrast_level=contrast,
        is_dark=dark,
        primary_palette=palette(SEEDS["primary"], chroma=40.0),
        secondary_palette=palette(SEEDS["secondary"], chroma=18.0),
        tertiary_palette=palette(SEEDS["tertiary"], chroma=40.0),
        neutral_palette=TonalPalette.from_hue_and_chroma(*NEUTRAL),
        neutral_variant_palette=TonalPalette.from_hue_and_chroma(*NEUTRAL_VARIANT),
    )


def hex_color(argb: int) -> str:
    return f"Color(0xFF{argb & 0xFFFFFF:06X})"


def scheme_kotlin(name: str, factory: str, s: DynamicScheme) -> str:
    lines = [f"internal val {name} = {factory}("]
    lines += [f"    {role} = {hex_color(getattr(M, role).get_argb(s))}," for role in ROLES]
    lines.append(")")
    return "\n".join(lines)


def extended_kotlin(name: str, dark: bool) -> str:
    tones = (80, 20, 30, 90) if dark else (40, 100, 90, 10)
    lines = [f"internal val {name} = HitzExtendedColors("]
    for key, seed in EXTENDED.items():
        p = palette(seed, chroma=EXTENDED_CHROMA.get(key))
        c, on, cont, on_cont = (p.tone(t) for t in tones)
        lines.append(
            f"    {key} = ColorFamily({hex_color(c)}, {hex_color(on)}, {hex_color(cont)}, {hex_color(on_cont)}),"
        )
    lines.append(")")
    return "\n".join(lines)


def main() -> None:
    parts = [
        "// GENERATED by tools/design/generate_color_scheme.py. Do not edit by hand.",
        "@file:Suppress(\"MagicNumber\")",
        "",
        "package eus.hitz.core.designsystem.theme",
        "",
        "import androidx.compose.material3.darkColorScheme",
        "import androidx.compose.material3.lightColorScheme",
        "import androidx.compose.ui.graphics.Color",
        "",
        scheme_kotlin("LightColorScheme", "lightColorScheme", scheme(False, 0.0)),
        "",
        scheme_kotlin("DarkColorScheme", "darkColorScheme", scheme(True, 0.0)),
        "",
        scheme_kotlin("LightHighContrastColorScheme", "lightColorScheme", scheme(False, 1.0)),
        "",
        scheme_kotlin("DarkHighContrastColorScheme", "darkColorScheme", scheme(True, 1.0)),
        "",
        extended_kotlin("LightExtendedColors", dark=False),
        "",
        extended_kotlin("DarkExtendedColors", dark=True),
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
