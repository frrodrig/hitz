package eus.hitz.core.designsystem.component

import androidx.compose.foundation.layout.size
import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.remember
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.semantics.clearAndSetSemantics
import androidx.compose.ui.unit.dp
import com.airbnb.lottie.LottieCompositionFactory
import com.airbnb.lottie.compose.LottieAnimation
import com.airbnb.lottie.compose.animateLottieCompositionAsState
import eus.hitz.core.designsystem.R
import eus.hitz.core.designsystem.motion.rememberReducedMotion

/**
 * A one-shot confetti burst (original Lottie animation, generated by
 * tools/design/make_celebration.py). Decorative: hidden from TalkBack, and not shown at all when
 * the learner has turned animations off.
 */
@Composable
fun HitzCelebration(modifier: Modifier = Modifier) {
    if (rememberReducedMotion()) return
    val context = LocalContext.current
    // The file is tiny: loading it synchronously keeps the first frame (and screenshots) stable.
    val composition = remember(context) {
        LottieCompositionFactory.fromRawResSync(context, R.raw.core_designsystem_celebration).value
    }
    val progress by animateLottieCompositionAsState(composition, iterations = 1)
    LottieAnimation(
        composition = composition,
        progress = { progress },
        modifier = modifier
            .size(240.dp)
            .clearAndSetSemantics {},
    )
}
