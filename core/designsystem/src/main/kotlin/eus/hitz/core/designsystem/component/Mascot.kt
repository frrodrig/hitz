/** Width / height of the cast's drawings (240 × 280 viewport). */
private const val ASPECT = 240f / 280f

/** How much of a framed member's container the drawing fills. */
private const val FRAMED_FILL = 0.92f

/**
 * The four Basque friends who talk to the learner, one per arm of the lauburu in the app icon.
 * Each one has a role, so the same person always appears in the same kind of moment.
 */
enum class CastMember(@param:StringRes val description: Int) {
    /** Trikitilari, red. The guide: lesson prompts, unit introductions, onboarding. */
    Ane(R.string.core_designsystem_cast_ane),

    /** Aizkolari, blue. The coach: the end of a lesson, streaks, levels passed. */
    Mikel(R.string.core_designsystem_cast_mikel),

    /** Amona, ochre. The teacher: mistakes, corrections, grammar and hints. */
    Maite(R.string.core_designsystem_cast_maite),

    /** Pelotari, sea green. The rival: practice, challenges and goals. */
    Unai(R.string.core_designsystem_cast_unai),
    ;

    companion object {
        /** Who says what by default: Ane greets, Mikel celebrates, Maite corrects and explains. */
        fun speakerFor(pose: MascotPose): CastMember = when (pose) {
            MascotPose.Hola -> Ane
            MascotPose.Bien -> Mikel
            MascotPose.Ups, MascotPose.Piensa -> Maite
        }
    }
}

/**
 * What a [CastMember] is doing. Every member has the four poses, drawn in
 * `tools/design/art/cast/` and generated by `tools/design/cast_to_vector.py`.
 */
enum class MascotPose {
    /** Their own greeting: Ane plays the trikitixa, Mikel waves, Maite reads, Unai bounces the pelota. */
    Hola,

    /** Jumps with an arm up among sparkles: right answers, the end of a lesson. */
    Bien,

    /** A hand to the head, a shake of the head and a drop of sweat: wrong answers, errors. */
    Ups,

    /** A hand on the chin and thought bubbles: hints, empty states, loading. */
    Piensa,
}

/**
 * A member of the cast in a pose. [size] is the drawing's height. By default the pose picks who
 * appears ([CastMember.speakerFor]). With [framed] they sit on an expressive "sunny" shape, for
 * avatars and small sizes. Pass `contentDescription = null` when the drawing is decorative, which
 * is almost always.
 *
 * They are [animated] by default: each pose loops its own gestures, layer by layer. With reduced
 * motion, or `animated = false`, they stand still.
 */
@Composable
fun HitzMascot(
    modifier: Modifier = Modifier,
    pose: MascotPose = MascotPose.Hola,
    member: CastMember = CastMember.speakerFor(pose),
    size: Dp = 140.dp,
    framed: Boolean = false,
    contentDescription: String? = stringResource(member.description),
    animated: Boolean = true,
) {
    val art = CastArtwork.getValue(member).getValue(pose)
    val moving = animated && !rememberReducedMotion()
    if (framed) {
        Box(
            modifier = modifier
                .size(size)
                .clip(MaterialShapes.Sunny.toShape())
                .background(MaterialTheme.colorScheme.primaryContainer),
            contentAlignment = Alignment.BottomCenter,
        ) {
            CastImage(art, size * FRAMED_FILL, contentDescription, moving)
        }
    } else {
        CastImage(art, size, contentDescription, moving, modifier)
    }
}

@Composable
private fun CastImage(
    art: CastArt,
    height: Dp,
    contentDescription: String?,
    moving: Boolean,
    modifier: Modifier = Modifier,
) {
    val sized = modifier
        .height(height)
        .width(height * ASPECT)
    if (moving) {
        AnimatedCast(
            art = art,
            modifier = if (contentDescription == null) {
                sized
            } else {
                sized.semantics {
                    this.contentDescription = contentDescription
                    role = Role.Image
                }
            },
        )
    } else {
        Image(painter = painterResource(art.still), contentDescription = contentDescription, modifier = sized)
    }
}

@HitzPreviews
@Composable
private fun HitzMascotPreview() {
    HitzTheme {
        Column(verticalArrangement = Arrangement.spacedBy(HitzSpacing.sm)) {
            MascotPose.entries.forEach { pose ->
                Row(horizontalArrangement = Arrangement.spacedBy(HitzSpacing.sm)) {
                    CastMember.entries.forEach { HitzMascot(pose = pose, member = it, size = 96.dp) }
                }
            }
            Row(horizontalArrangement = Arrangement.spacedBy(HitzSpacing.sm)) {
                CastMember.entries.forEach { HitzMascot(member = it, size = 72.dp, framed = true) }
            }
        }
    }
}
