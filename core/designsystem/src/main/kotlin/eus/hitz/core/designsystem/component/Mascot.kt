/** Width / height of the mascot drawings (240 × 280 viewport). */
private const val ASPECT = 240f / 280f

/** How much of a framed mascot's container the drawing fills. */
private const val FRAMED_FILL = 0.92f

/** What the Galtzagorri is doing. Each pose is a drawing generated by `tools/design/mascot_to_vector.py`. */
enum class MascotPose(@DrawableRes val drawable: Int) {
    /** Waves with one hand and holds the makila with the other: introductions, the lesson prompt. */
    Hola(R.drawable.core_designsystem_mascot_hola),

    /** Jumps with the makila up: right answers, the end of a lesson. */
    Bien(R.drawable.core_designsystem_mascot_bien),

    /** Scratches his head: wrong answers, errors. */
    Ups(R.drawable.core_designsystem_mascot_ups),

    /** Strokes his beard: hints, loading. */
    Piensa(R.drawable.core_designsystem_mascot_piensa),
}

/**
 * The Galtzagorri mascot: a flat, geometric Basque helper with a txapela, a bushy beard, a makila
 * and the red trousers he is named after. [size] is the drawing's height. With [framed] he sits on
 * an expressive "sunny" shape, for avatars and small sizes. Pass `contentDescription = null` when
 * he is decorative, which is almost always.
 */
@Composable
fun HitzMascot(
    modifier: Modifier = Modifier,
    pose: MascotPose = MascotPose.Hola,
    size: Dp = 140.dp,
    framed: Boolean = false,
    contentDescription: String? = stringResource(R.string.core_designsystem_mascot_description),
) {
    if (framed) {
        Box(
            modifier = modifier
                .size(size)
                .clip(MaterialShapes.Sunny.toShape())
                .background(MaterialTheme.colorScheme.primaryContainer),
            contentAlignment = Alignment.BottomCenter,
        ) {
            MascotImage(pose, size * FRAMED_FILL, contentDescription)
        }
    } else {
        MascotImage(pose, size, contentDescription, modifier)
    }
}

@Composable
private fun MascotImage(pose: MascotPose, height: Dp, contentDescription: String?, modifier: Modifier = Modifier) {
    Image(
        painter = painterResource(pose.drawable),
        contentDescription = contentDescription,
        modifier = modifier
            .height(height)
            .width(height * ASPECT),
    )
}

@HitzPreviews
@Composable
private fun HitzMascotPreview() {
    HitzTheme {
        Row(horizontalArrangement = Arrangement.spacedBy(HitzSpacing.sm), verticalAlignment = Alignment.Bottom) {
            MascotPose.entries.forEach { HitzMascot(pose = it, size = 120.dp, contentDescription = null) }
            HitzMascot(size = 72.dp, framed = true, contentDescription = null)
        }
    }
}
