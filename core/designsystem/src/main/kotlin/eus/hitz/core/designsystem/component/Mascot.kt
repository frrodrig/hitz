/**
 * The Galtzagorri mascot: a flat, geometric Basque helper with a txapela, a bushy beard, a makila
 * and the red trousers he is named after. [size] is the drawing's height. With [framed] he sits on
 * an expressive "sunny" shape, for avatars and small sizes. Pass `contentDescription = null` when
 * he is decorative, which is almost always.
 *
 * He is [animated] by default: he breathes and blinks, and each pose adds a gesture (Hola waves,
 * Bien jumps and wiggles, Ups shakes his head, Piensa sways while his thoughts float). With reduced
 * motion, or `animated = false`, he stands still.
 */
@Composable
fun HitzMascot(
    modifier: Modifier = Modifier,
    pose: MascotPose = MascotPose.Hola,
    size: Dp = 140.dp,
    framed: Boolean = false,
    contentDescription: String? = stringResource(R.string.core_designsystem_mascot_description),
    animated: Boolean = true,
) {
    val moving = animated && !rememberReducedMotion()
    if (framed) {
        Box(
            modifier = modifier
                .size(size)
                .clip(MaterialShapes.Sunny.toShape())
                .background(MaterialTheme.colorScheme.primaryContainer),
            contentAlignment = Alignment.BottomCenter,
        ) {
            MascotImage(pose, size * FRAMED_FILL, contentDescription, moving)
        }
    } else {
        MascotImage(pose, size, contentDescription, moving, modifier)
    }
}

@Composable
private fun MascotImage(
    pose: MascotPose,
    height: Dp,
    contentDescription: String?,
    moving: Boolean,
    modifier: Modifier = Modifier,
) {
    val sized = modifier
        .height(height)
        .width(height * ASPECT)
    if (moving) {
        AnimatedMascot(
            pose = pose,
            modifier = if (contentDescription == null) {
                sized
            } else {
                sized.semantics {
                    this.contentDescription = contentDescription
                    role = Role.Image
                }
            },
        )
    } else {
        Image(painter = painterResource(pose.drawable), contentDescription = contentDescription, modifier = sized)
    }
}

@HitzPreviews
@Composable
private fun HitzMascotPreview() {
    HitzTheme {
        Row(horizontalArrangement = Arrangement.spacedBy(HitzSpacing.sm), verticalAlignment = Alignment.Bottom) {
            MascotPose.entries.forEach { HitzMascot(pose = it, size = 120.dp, contentDescription = null) }
            HitzMascot(size = 72.dp, framed = true, contentDescription = null)
        }
    }
}
